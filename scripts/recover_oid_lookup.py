def canonical(value):return json.dumps(value,separators=(',',':')).encode()
def original_bytes(image,address,size):
    segment=next(s for s in image.segments if s['vmaddr']<=address and address+size<=s['vmaddr']+s['vmsize'])
    off=address-segment['vmaddr'];backed=max(0,min(size,segment['filesize']-off))
    return image.data[segment['fileoff']+off:segment['fileoff']+off+backed]+bytes(size-backed)
def extract_database(image):
    objects=[];ranges=[]
    for i in range(958):
        raw=original_bytes(image,OBJECTS+i*40,40);sn,ln,nid,length,data,flags=struct.unpack('<QQiiQi4x',raw)
        require(raw[36:]==bytes(4),'Unexpected original ASN1_OBJECT padding')
        obj={'short_address':sn,'long_address':ln,'nid':nid,'length':length,'data_address':data,'flags':flags,'encoded':original_bytes(image,data,length).hex() if data else ''}
        for name,address in [('short',sn),('long',ln)]:
            value=image.cstr(address) if address else None;obj[name]=value
            if address:ranges.append((address,address+len(value.encode())+1))
        if data:require(length>0,'Unexpected OID content length');ranges.append((data,data+length))
        objects.append(obj)
    merged=[]
    for start,end in sorted(ranges):
        if merged and start<=merged[-1][1]:merged[-1][1]=max(end,merged[-1][1])
        else:merged.append([start,end])
    pools=[{'address':hex(a),'bytes':original_bytes(image,a,b-a).hex()} for a,b in merged]
    memory=[{'address':hex(OBJECTS),'bytes':original_bytes(image,OBJECTS,958*40).hex()},{'address':hex(SEARCH),'bytes':original_bytes(image,SEARCH,890*4).hex()},*pools]
    return {'objects':objects,'search':list(struct.unpack('<890I',original_bytes(image,SEARCH,890*4))),'pools':pools,'memory':memory}
