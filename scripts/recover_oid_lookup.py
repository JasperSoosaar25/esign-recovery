def render_data(db):
    text=['/* Exact original public OID constants, relocated from the pinned IPA. */','/* Legacy OpenSSL notices: OPENSSL-LICENSE.txt. Generated by recover_oid_lookup.py. */','#include "ESignOIDLookup.h"']
    for i,pool in enumerate(db['pools']):
        raw=bytes.fromhex(pool['bytes']);text.append('static const unsigned char OIDPool'+str(i)+'[] = {')
        for offset in range(0,len(raw),20):text.append('    '+','.join('0x%02x'%b for b in raw[offset:offset+20])+',')
        text.append('};')
    def pointer(address,cast):
        if not address:return 'NULL'
        for i,pool in enumerate(db['pools']):
            start=int(pool['address'],16);size=len(pool['bytes'])//2
            if start<=address<start+size:return '('+cast+')(OIDPool'+str(i)+'+'+str(address-start)+')'
        raise ValueError('Uncaptured original OID pointer')
    text.append('ESignOIDObject ESignOriginalOIDObjects[958] = {')
    for o in db['objects']:text.append('    {'+','.join([pointer(o['short_address'],'const char *'),pointer(o['long_address'],'const char *'),str(o['nid']),str(o['length']),pointer(o['data_address'],'const unsigned char *'),str(o['flags'])])+'},')
    text.append('};');text.append('const uint32_t ESignOriginalOIDSearch[890] = {')
    for offset in range(0,890,20):text.append('    '+','.join(str(v) for v in db['search'][offset:offset+20])+',')
    return '\n'.join([*text,'};',''])
def extra_inputs(db):return {**{int(r['address'],16):bytes.fromhex(r['bytes']) for r in db['memory']},ADDED:bytes(8),FILENAME:b'obj_dat.c\0'}
def records(image,dispatch):
    starts,branches=boundaries_and_branches();result=[]
    for role,entry in ENTRIES.items():
        r=walk(image.data,entry,starts,branches,image=image,dispatch=dispatch)
        require(not r['unresolved_indirect_jumps'] and not r['boundary_stops'],'Incomplete original OID flow')
        result.append(dict(r,role=role))
    return result
class OIDMachine(Scenario,CryptoMachine):
    def __init__(self,chunks,flows,metadata,db):
        CryptoMachine.__init__(self,chunks,flows,{}, {},metadata);self.static_labels={}
        for i,o in enumerate(db['objects']):
            self.static_labels[OBJECTS+i*40]='static-object-'+str(i)
            for field in ['short_address','long_address','data_address']:
                if o[field]:self.static_labels[o[field]]='static-'+hex(o[field])
        self.objects_address=OBJECTS;self.hash_pointer=GUARD+0x100;self.compare_pointer=GUARD+0x110
    def reset_heap(self):self.next_token=HEAP;self.tokens={};self.objects={}
    def raw(self,name,size=256):return CryptoMachine.raw(self,name,size)
    def read_bytes(self,p,n):return bytes(self.uc.mem_read(p,n))
    def write_bytes(self,p,raw):self.uc.mem_write(p,raw)
    def set_added(self,p):self.put64(ADDED,p)
    def boundary(self,target,args):
        if target==self.hash_pointer:return self.hash_callback(args[0])
        if target==self.compare_pointer:return self.compare_callback(args[0],args[1])
        if target==0x100604c0c:self.error_callback(*args);return 0
        require(target==0x10093122c and args[2]<=256,'Unexpected OID boundary or comparison size')
        a,b=(self.read_bytes(p,args[2]) for p in args[:2]);return ((a>b)-(a<b))&0xffffffff
